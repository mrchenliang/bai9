export function creditById(id: string | undefined): Credit | undefined {
  return credits.find((credit) => credit.id === id);
}

export function brandById(id: string): Brand | undefined {
  return brands.find((brand) => brand.id === id);
}

export function skuById(id: string): Sku | undefined {
  return skus.find((sku) => sku.id === id);
}

export function skusForBrand(id: string): Sku[] {
  return skus.filter((sku) => sku.brandId === id);
}

export function aromaById(id: string): Aroma | undefined {
  return aromas.find((aroma) => aroma.id === id);
}

export function skuAroma(sku: Sku): Aroma | undefined {
  const brand = brandById(sku.brandId);
  return aromaById(sku.aroma ?? brand?.aroma ?? "nong");
}

export function tierById(id: string): Tier | undefined {
  return tiers.find((tier) => tier.id === id);
}

